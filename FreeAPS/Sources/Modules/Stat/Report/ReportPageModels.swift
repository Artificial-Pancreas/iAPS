import Foundation

// The pages of a report, formatted for print: only strings and plots are built here, on the main actor
// (`StatsFormatting`), from `Stat.ReportData`. The numbers are the data's (computed once); a page's unit only decides
// how values and range labels are written.

extension Stat.StatsSettings {
    /// A report page's: the standard bands of its unit, the user's HbA1c unit.
    init(report units: GlucoseUnits, hbA1cUnit: HbA1cUnit) {
        bands = Stat.ReportBuilder.standardBands(units)
        self.units = units
        self.hbA1cUnit = hbA1cUnit
    }
}

extension Stat {
    /// What every page of a report has around its content: the header and the footer.
    struct ReportPageChrome: Equatable {
        /// the part's
        let title: String
        /// "8 Nov 2026 – 21 Nov 2026"
        let dateRange: String
        /// "12 of 14 days with data"
        let days: String
        /// "Ranges (mg/dL): very low < 54 · low 54–69 · in range 70–180 · high 181–250 · very high > 250 · TITR 70–140";
        /// empty on a part without glucose (Insulin, Meals): no line
        let ranges: String
        /// "Generated by iAPS 5.2.0 · 21 Nov 2026 at 14:35 · Time in ranges is time-weighted"
        let provenance: String
        /// "Page 1 of 2"
        let pageNumber: String

        /// A day as the header writes it, in the calendar's time zone.
        static func dayStyle(_ calendar: Calendar) -> Date.FormatStyle {
            var style = Date.FormatStyle.dateTime.day().month(.abbreviated).year()
            style.timeZone = calendar.timeZone
            return style
        }

        /// - Parameters:
        ///   - index: the page's, from 0
        ///   - count: the report's pages
        ///   - calendar: the period's days' (and the time zone the dates are written in)
        ///   - header: the part's own dates (`ReportPageContent.header`); nil: the report's period
        @MainActor init(
            _ data: ReportData,
            page: ReportPage,
            index: Int,
            count: Int,
            version: String,
            calendar: Calendar = .current,
            header: ReportPageHeader? = nil
        ) {
            typealias Format = StatsFormatting
            let units = page.units
            let bands = ReportBuilder.standardBands(units)

            title = page.part.title
            let days = data.days(calendar: calendar)
            let dayStyle = Self.dayStyle(calendar)
            // a part with days of its own (whole weeks, complete days) says them; the others the report's period
            dateRange = header?.dateRange ?? String(
                format: NSLocalizedString("%@ – %@", comment: "Statistics date range, first and last day"),
                days.first.formatted(dayStyle),
                days.last.formatted(dayStyle)
            )
            self.days = header?.days ?? String(
                format: NSLocalizedString(
                    "%1$d of %2$d days with data",
                    comment: "PDF report header: the days with CGM readings, of the period's days"
                ),
                data.summary.daysWithData,
                data.summary.calendarDays
            )
            func label(_ band: GlucoseBand) -> String {
                Format.label(band, bands: bands, units: units) ?? "–"
            }
            ranges = !page.part.printsGlucose ? "" : String(
                format: NSLocalizedString(
                    "Ranges (%1$@): very low %2$@ · low %3$@ · in range %4$@ · high %5$@ · very high %6$@ · TITR %7$@",
                    comment: "PDF report header: the unit, then the glucose ranges every report uses"
                ),
                Format.unit(units),
                label(.veryLow),
                label(.low),
                label(.inRange),
                label(.high),
                label(.veryHigh),
                Format.range(bands.titrRange, units: units)
            )
            var timeStyle = Date.FormatStyle(date: .abbreviated, time: .shortened)
            timeStyle.timeZone = calendar.timeZone
            // what the time in ranges is belongs under glucose: not on a part without any
            provenance = page.part.printsGlucose
                ? String(
                    format: NSLocalizedString(
                        "Generated by iAPS %1$@ · %2$@ · Time in ranges is time-weighted",
                        comment: "PDF report footer: the app version, the date and time the report was made"
                    ),
                    version,
                    data.generatedAt.formatted(timeStyle)
                )
                : String(
                    format: NSLocalizedString(
                        "Generated by iAPS %1$@ · %2$@",
                        comment: "PDF report footer of a part without glucose: the app version, the date and time the report was made"
                    ),
                    version,
                    data.generatedAt.formatted(timeStyle)
                )
            pageNumber = String(
                format: NSLocalizedString("Page %1$d of %2$d", comment: "PDF report footer: the page, the report's pages"),
                index + 1,
                count
            )
        }
    }

    /// A consensus goal beside a number: "Goal >70%", and whether the exact value meets it.
    struct ReportGoalMark: Equatable {
        let text: String
        let isMet: Bool

        /// ">70%", "<4%", "≤36%", "≥14"
        static func target(_ goal: ReportGoal) -> String {
            let sign: String
            switch goal.comparison {
            case .moreThan: sign = ">"
            case .lessThan: sign = "<"
            case .atMost: sign = "≤"
            case .atLeast: sign = "≥"
            }
            return sign + "\(goal.threshold)" + (goal.isPercent ? "%" : "")
        }

        /// "Goal >70%"; nil without data
        init?(_ goal: ReportGoal, summary: GlucoseSummary) {
            guard let isMet = goal.isMet(summary) else { return nil }
            text = String(
                format: NSLocalizedString("Goal %@", comment: "PDF report: a consensus goal beside a number, \"Goal >70%\""),
                Self.target(goal)
            )
            self.isMet = isMet
        }

        /// "Below 70: 4% · goal <4%": a goal on two ranges together, with their time as one percent (the sum of the
        /// fractions, rounded once: not the sum of the rows' percents); "<1%" for a nonzero one that rounds to 0.
        init?(_ goal: ReportGoal, summary: GlucoseSummary, combined label: String) {
            guard let value = goal.value(summary) else { return nil }
            let rounded = Int(value.rounded())
            text = String(
                format: NSLocalizedString(
                    "%1$@: %2$@ · goal %3$@",
                    comment: "PDF report: a consensus goal on two ranges together, \"Below 70: 3% · goal <4%\""
                ),
                label,
                value > 0 && rounded == 0 ? "<1%" : "\(rounded)%",
                Self.target(goal)
            )
            isMet = goal.isMet(value)
        }
    }

    /// The percentile chart of a report, on its fixed scale.
    struct ReportPercentilePlot: Equatable {
        struct Level: Equatable, Identifiable {
            let mgdl: Int
            let label: String

            var id: Int { mgdl }
        }

        typealias Tick = AGP.Plot.Tick

        /// the x axis: the minutes of the day
        static let dayMinutes = 24 * 60

        /// mg/dL
        let axis: ClosedRange<Int>
        /// kept inside the axis (`GlucoseStatsEngine.agpPlotPoints`)
        let points: [AGPPlotPoint]
        /// the in-range band's edges (70 and 180), drawn in its colour
        let edges: [Int]
        /// the labelled levels, ascending; a thin rule at each that isn't an edge
        let levels: [Level]
        /// the labelled times, every `hourStep` hours from 00:00 (the day's end has none)
        let xTicks: [Tick]
        /// a rule at each, the day's end included
        let gridMinutes: [Int]
        let unit: String

        /// The fixed scale: 0–350 mg/dL (mmol/L: 0–360, shown as 20.0), raised in steps (50; 36, 2.0 mmol/L) only when
        /// the 95th percentile is above it.
        /// - Parameter highest: the highest 95th percentile, nil without data
        static func axis(highest: Double?, units: GlucoseUnits) -> ClosedRange<Int> {
            let step = units == .mmolL ? 36 : 50
            var top = units == .mmolL ? 360 : 350
            while Double(top) < (highest ?? 0), top + step <= GlucoseHistogram.maxValue + step {
                top += step
            }
            return 0 ... top
        }

        /// The labelled levels, ascending: taken in order of importance (70, 180, the top, 250, 54, 0), one closer than
        /// `minimumGap` (of the axis) to one already taken is left out.
        static func levels(bands: StatsBands, axis: ClosedRange<Int>, minimumGap: Double) -> [Int] {
            let candidates = [
                bands.low,
                bands.high,
                axis.upperBound,
                StatsBands.veryHighAbove,
                StatsBands.veryLowBelow,
                axis.lowerBound
            ]
            let gap = Double(axis.upperBound - axis.lowerBound) * minimumGap
            var taken: [Int] = []
            for value in candidates where axis.contains(value) {
                guard taken.allSatisfy({ Double(abs($0 - value)) >= gap }) else { continue }
                taken.append(value)
            }
            return taken.sorted()
        }

        /// - Parameters:
        ///   - bands: the page's unit's standard ones (the edges drawn and labelled)
        ///   - units: the page's (the labels, the scale's top)
        ///   - hourStep: a labelled time every so many hours
        ///   - minimumGap: `levels`'
        @MainActor init(bins: [AGPBin?], bands: StatsBands, units: GlucoseUnits, hourStep: Int, minimumGap: Double) {
            let axis = Self.axis(highest: bins.compactMap { $0?.p95 }.max(), units: units)
            self.axis = axis
            points = GlucoseStatsEngine.agpPlotPoints(bins, axis: axis)
            edges = bands.low == bands.high ? [bands.low] : [bands.low, bands.high]
            levels = Self.levels(bands: bands, axis: axis, minimumGap: minimumGap)
                .map { Level(mgdl: $0, label: StatsFormatting.glucose($0, units: units)) }
            let step = Swift.max(hourStep, 1) * 60
            let minutes = Array(stride(from: 0, through: Self.dayMinutes, by: step))
            gridMinutes = minutes
            xTicks = minutes.filter { $0 < Self.dayMinutes }.map { Tick(minute: $0, label: AGP.clockTime($0)) }
            unit = StatsFormatting.unit(units)
        }
    }

    /// The colour key under a percentile chart.
    struct ReportPercentileLegend: Equatable {
        /// "5–95%"
        let outer: String
        /// "25–75%"
        let inner: String
        let median: String
        /// "Range 70–180 mg/dL"
        let range: String

        @MainActor init(units: GlucoseUnits) {
            outer = StatsFormatting.percentileBand(5, 95)
            inner = StatsFormatting.percentileBand(25, 75)
            median = NSLocalizedString("Median", comment: "Statistics AGP, the 50th percentile")
            range = String(
                format: NSLocalizedString("Range %@", comment: "PDF report, percentile chart legend: the in-range band"),
                StatsFormatting.inRangeLabel(bands: ReportBuilder.standardBands(units), units: units)
            )
        }
    }

    /// The Summary page.
    struct ReportSummary: Equatable {
        typealias Goal = ReportGoalMark

        /// A band of the time in ranges, very high first (the bar's order, top down).
        struct RangeRow: Equatable, Identifiable {
            let band: GlucoseBand
            let name: String
            /// "70–180"
            let range: String
            let percent: String
            /// "2 h 05 m"
            let perDay: String
            let goal: Goal?

            var id: GlucoseBand { band }
        }

        struct Metric: Equatable, Identifiable {
            let id: Int
            let title: String
            /// with its unit: "154 mg/dL"
            let value: String
            var goal: Goal?
        }

        /// A column of the insulin and carbs block.
        struct Amount: Equatable, Identifiable {
            let id: Int
            let title: String
            /// "38.2 U", "182 g", "–"
            let value: String
            /// "45%"; empty without
            var detail = ""
        }

        struct InsulinAndCarbs: Equatable {
            /// TDD, basal, SMB, bolus, carbs
            let amounts: [Amount]
            /// what the averages are over, and what couldn't be read
            let notes: [String]
        }

        /// the consensus minimum of days: a shorter period has no days goal to meet
        static let minimumDays = ReportGoal.days.threshold

        let unit: String
        /// the nonzero bands, very high first
        let segments: [BandSegment]
        /// very high first
        let rows: [RangeRow]
        let metrics: [Metric]
        /// under the metrics when the period has fewer than 14 days with data or less than 70% CGM active
        let limitedNote: String?
        let plot: ReportPercentilePlot
        let legend: ReportPercentileLegend
        /// nil when the block is off
        let insulinAndCarbs: InsulinAndCarbs?

        /// - Parameter units: the page's: how the values and the ranges are written
        @MainActor init(_ data: ReportData, units: GlucoseUnits) {
            typealias Format = StatsFormatting
            let summary = data.summary
            // the ranges as the page's unit writes them; the numbers are the data's
            let labels = ReportBuilder.standardBands(units)
            let settings = StatsSettings(report: units, hbA1cUnit: data.request.hbA1cUnit)
            // the Overview's numbers, formatted by it
            let numbers = Overview(summary, period: data.request.period, settings: settings)
            unit = numbers.unit

            let order = Array(GlucoseBand.allCases.reversed())
            segments = summary.bandShares.barSegments(order)
            let goals: [GlucoseBand: Goal?] = [
                .veryHigh: Goal(.above250, summary: summary),
                .high: Goal(
                    .above180,
                    summary: summary,
                    combined: String(
                        format: NSLocalizedString("Above %@", comment: "PDF report: the time above the in-range band's top"),
                        Format.glucose(labels.high, units: units)
                    )
                ),
                .inRange: Goal(.inRange, summary: summary),
                .low: Goal(
                    .below70,
                    summary: summary,
                    combined: String(
                        format: NSLocalizedString("Below %@", comment: "PDF report: the time below the in-range band's bottom"),
                        Format.glucose(labels.low, units: units)
                    )
                ),
                .veryLow: Goal(.below54, summary: summary)
            ]
            rows = order.map { band in
                RangeRow(
                    band: band,
                    name: Format.name(band),
                    range: Format.label(band, bands: labels, units: units) ?? "",
                    percent: Format.percent(band, of: summary),
                    perDay: Format.perDay(summary.fraction(band)),
                    goal: goals[band] ?? nil
                )
            }

            func withUnit(_ value: String, _ unit: String, spaced: Bool = true) -> String {
                value == "–" ? value : value + (spaced ? " " : "") + unit
            }
            let a1cSpaced = numbers.a1cUnit != "%"
            // a period shorter than the minimum can't meet it: the count alone
            let daysGoal = (data.request.period.calendarDayCount ?? 0) >= Self.minimumDays
                ? Goal(.days, summary: summary)
                : nil
            var metrics: [Metric] = [
                Metric(
                    id: 0,
                    title: NSLocalizedString("Mean", comment: "Statistics, mean glucose"),
                    value: withUnit(numbers.mean, numbers.unit)
                ),
                Metric(
                    id: 1,
                    title: NSLocalizedString("GMI", comment: "Glucose management indicator"),
                    value: withUnit(numbers.gmi, numbers.a1cUnit, spaced: a1cSpaced)
                ),
                Metric(
                    id: 2,
                    title: NSLocalizedString("eA1c", comment: "Estimated A1c (ADAG)"),
                    value: withUnit(numbers.eA1c, numbers.a1cUnit, spaced: a1cSpaced)
                ),
                Metric(id: 3, title: NSLocalizedString("SD", comment: ""), value: withUnit(numbers.sd, numbers.unit)),
                Metric(
                    id: 4,
                    title: NSLocalizedString("CV", comment: ""),
                    value: numbers.cv,
                    goal: Goal(.cv, summary: summary)
                ),
                Metric(id: 5, title: Format.tirTitle(bands: labels, units: units), value: numbers.tir),
                Metric(id: 6, title: Format.titrTitle(bands: labels, units: units), value: numbers.titr),
                Metric(
                    id: 7,
                    title: NSLocalizedString("CGM active", comment: "PDF report: the share of the period with CGM readings"),
                    value: numbers.coverage,
                    goal: Goal(.cgmActive, summary: summary)
                ),
                Metric(
                    id: 8,
                    title: NSLocalizedString("Days with data", comment: "Statistics"),
                    value: numbers.daysWithData,
                    goal: daysGoal
                )
            ]
            if let gri = data.gri {
                metrics.append(
                    Metric(
                        id: 9,
                        title: NSLocalizedString("Glycemia Risk Index", comment: "PDF report: the GRI"),
                        value: String(
                            format: NSLocalizedString(
                                "%1$@ · zone %2$@",
                                comment: "PDF report: the GRI's value and its zone (A–E)"
                            ),
                            "\(Int(gri.value.rounded()))",
                            gri.zone.letter
                        )
                    )
                )
            }
            self.metrics = metrics

            let isLimited = ReportGoal.days.isMet(summary) == false || ReportGoal.cgmActive.isMet(summary) == false
            limitedNote = isLimited
                ? NSLocalizedString(
                    "Limited data: the period has fewer than 14 days with data or less than 70% CGM active.",
                    comment: "PDF report: the data sufficiency goals aren't met"
                )
                : nil

            // the edges as the page writes them (10.0 mmol/L is 181, a point from 180: the same rule on paper)
            plot = ReportPercentilePlot(bins: data.bins, bands: labels, units: units, hourStep: 6, minimumGap: 0.1)
            legend = ReportPercentileLegend(units: units)
            insulinAndCarbs = Self.insulinAndCarbs(data)
        }

        /// The insulin per day (the Insulin tab's headline: complete days) and the carbs per day (the Meals tab's:
        /// complete days with entries); nil when the block is off.
        @MainActor private static func insulinAndCarbs(_ data: ReportData) -> InsulinAndCarbs? {
            guard data.request.summary.insulinAndCarbs, data.insulin != nil || data.meals != nil else { return nil }
            typealias Format = StatsFormatting
            var notes: [String] = []
            var amounts: [Amount] = []

            let insulin = data.insulin?.value
            let hasInsulin = insulin.map { !$0.isEmpty && $0.tdd != nil } ?? false
            amounts.append(
                Amount(
                    id: 0,
                    title: NSLocalizedString("Total daily dose", comment: "Statistics Insulin: the TDD"),
                    value: insulin?.tdd.map { StatsAmount.units($0, digits: 1) } ?? "–"
                )
            )
            let means: [Double?] = [insulin?.basal, insulin?.smb, insulin?.bolus]
            for part in InsulinPart.allCases {
                amounts.append(
                    Amount(
                        id: part.rawValue + 1,
                        title: part.name,
                        value: means[part.rawValue].map { StatsAmount.units($0, digits: 1) } ?? "–",
                        detail: hasInsulin ? Format.percent(insulin?.splitPercents[part.rawValue] ?? 0) : ""
                    )
                )
            }
            if let insulin {
                if insulin.isEmpty {
                    notes.append(NSLocalizedString("No pump data in this period", comment: ""))
                } else if insulin.needsCompleteDay {
                    notes.append(NSLocalizedString("Needs one complete day", comment: "Statistics Insulin: no complete day yet"))
                } else if insulin.headlineDays == 1 {
                    notes.append(
                        NSLocalizedString(
                            "Insulin: 1 complete day with pump data",
                            comment: "PDF report: the insulin per day is one day's"
                        )
                    )
                } else {
                    notes.append(
                        String(
                            format: NSLocalizedString(
                                "Insulin: the mean of %d complete days with pump data",
                                comment: "PDF report: the days the insulin per day is over"
                            ),
                            insulin.headlineDays
                        )
                    )
                }
            } else {
                notes.append(NSLocalizedString("The pump data couldn't be read.", comment: ""))
            }

            let meals = data.meals?.value
            amounts.append(
                Amount(
                    id: 4,
                    title: NSLocalizedString("Carbs", comment: ""),
                    value: meals?.carbsPerDay.map { StatsAmount.grams($0, digits: 0) } ?? "–"
                )
            )
            if let meals {
                if meals.isEmpty {
                    notes.append(NSLocalizedString("No carb entries in this period", comment: ""))
                } else if meals.daysWithEntries == 1 {
                    notes.append(
                        NSLocalizedString(
                            "Carbs: 1 complete day with entries",
                            comment: "PDF report: the carbs per day are one day's"
                        )
                    )
                } else {
                    notes.append(
                        String(
                            format: NSLocalizedString(
                                "Carbs: the mean of %d complete days with entries",
                                comment: "PDF report: the days the carbs per day are over"
                            ),
                            meals.daysWithEntries
                        )
                    )
                }
            } else {
                notes.append(NSLocalizedString("The carb entries couldn't be read.", comment: ""))
            }
            return InsulinAndCarbs(amounts: amounts, notes: notes)
        }
    }

    /// The Percentile profile page.
    struct ReportPercentile: Equatable {
        /// A percentile across the day.
        struct Row: Equatable, Identifiable {
            let id: Int
            /// "95%", "Median"
            let title: String
            /// by `times`; "–" for a time without data
            let values: [String]
        }

        /// the table's step
        static let tableHours = 3

        let plot: ReportPercentilePlot
        let legend: ReportPercentileLegend
        /// "Percentiles by time of day (mg/dL)"
        let tableTitle: String
        /// "00:00", "03:00", …
        let times: [String]
        /// the 95th percentile first
        let rows: [Row]
        /// the profile's limited-data note (`StatsFormatting.profileNote`); nil when it isn't limited
        let limitedNote: String?

        /// - Parameter units: the page's
        @MainActor init(_ data: ReportData, units: GlucoseUnits) {
            typealias Format = StatsFormatting
            plot = ReportPercentilePlot(
                bins: data.bins,
                bands: ReportBuilder.standardBands(units),
                units: units,
                hourStep: 3,
                minimumGap: 0.04
            )
            legend = ReportPercentileLegend(units: units)
            tableTitle = String(
                format: NSLocalizedString(
                    "Percentiles by time of day (%@)",
                    comment: "PDF report, percentile profile: the table's title, with the glucose unit"
                ),
                Format.unit(units)
            )

            let minutes = Array(stride(from: 0, to: ReportPercentilePlot.dayMinutes, by: Self.tableHours * 60))
            times = minutes.map { AGP.clockTime($0) }
            let bins = data.bins
            let picked: [AGPBin?] = minutes.map { minute -> AGPBin? in
                guard bins.isNotEmpty else { return nil }
                return bins[GlucoseStatsEngine.agpBin(atMinute: minute, binCount: bins.count)]
            }
            func row(_ id: Int, _ title: String, _ value: (AGPBin) -> Double) -> Row {
                Row(
                    id: id,
                    title: title,
                    values: picked.map { bin in bin.map { Format.glucose(value($0), units: units) } ?? "–" }
                )
            }
            rows = [
                row(0, Format.percent(95)) { $0.p95 },
                row(1, Format.percent(75)) { $0.p75 },
                row(2, NSLocalizedString("Median", comment: "Statistics AGP, the 50th percentile")) { $0.p50 },
                row(3, Format.percent(25)) { $0.p25 },
                row(4, Format.percent(5)) { $0.p5 }
            ]
            limitedNote = Format.profileNote(data.summary)
        }
    }

    /// A page's content, formatted.
    enum ReportPageContent: Equatable {
        case summary(ReportSummary)
        case percentile(ReportPercentile)
        case days(ReportDaysPage)
        case charts(ReportChartsPage)
        case hours(ReportHours)
        case weekdays(ReportWeekdays)
        case weeks(ReportWeeks)
        case goodBadDays(ReportGoodBadDays)
        case insulin(ReportInsulin)
        case meals(ReportMeals)

        /// The part's own header lines; nil: the report's period.
        var header: ReportPageHeader? {
            switch self {
            case let .weekdays(page): return page.header
            case let .weeks(page): return page.header
            case let .goodBadDays(page): return page.header
            case let .insulin(page): return page.header
            case let .meals(page): return page.header
            default: return nil
            }
        }

        /// Built when the page is drawn, one page at a time; nil for a part that isn't implemented.
        /// - Parameter calendar: the days' (the Days table's weeks and months, the charts' clock)
        ///   - dayRows: the Days table's rows page by page, when built for the report (`ReportData.Layout`)
        @MainActor init?(
            _ data: ReportData,
            page: ReportPage,
            dayRows: [[ReportDaysRow]]? = nil,
            calendar: Calendar = .current
        ) {
            switch page.part {
            case .summary: self = .summary(ReportSummary(data, units: page.units))
            case .percentileProfile: self = .percentile(ReportPercentile(data, units: page.units))
            case .daysTable: self = .days(ReportDaysPage(data, page: page, rows: dayRows, calendar: calendar))
            case .dailyCharts: self = .charts(ReportChartsPage(data, page: page, calendar: calendar))
            case .byHour:
                guard data.hourOfDay != nil else { return nil }
                self = .hours(ReportHours(data, units: page.units))
            case .byWeekday:
                guard let weekdays = ReportWeekdays(data, units: page.units, calendar: calendar) else { return nil }
                self = .weekdays(weekdays)
            case .weekly:
                guard let weeks = ReportWeeks(data, units: page.units, calendar: calendar) else { return nil }
                self = .weeks(weeks)
            case .goodBadDays:
                guard let days = ReportGoodBadDays(data, page: page, calendar: calendar) else { return nil }
                self = .goodBadDays(days)
            case .insulin: self = .insulin(ReportInsulin(data, page: page, calendar: calendar))
            case .meals: self = .meals(ReportMeals(data, page: page, calendar: calendar))
            default: return nil
            }
        }
    }
}
